"""10장 완전 풀이 예제: 점수 가중합, 헝가리 알고리즘, 가중치 민감도, 모호성 지수. 가상 지명 사전."""
import numpy as np, math
from scipy.optimize import linear_sum_assignment

W0 = (0.5, 0.3, 0.2)
# 언급: (이름, 연도 구간, 공간 힌트 좌표 km 또는 None)
MEN = [("m1 서도", (1090, 1110), (140, 150)),
       ("m2 북진", (1085, 1115), (110, 230)),
       ("m3 동관", (1150, 1190), None)]
# 기록: (이름, 존속 구간, 위치 km, 이름점수 행(언급별))
REC = [("r1", (1000, 1180), (125, 150)),
       ("r2", (1180, 1400), (300, 80)),
       ("r3", (1050, 1250), (105, 235)),
       ("r4", (1000, 1300), (200, 300))]
SN = np.array([[0.8, 0.1, 0.6, 0.1],
               [0.1, 0.1, 1.0, 0.8],
               [1.0, 0.8, 0.1, 0.6]])
H = 50.0

def s_time(a, b):
    ov = max(0, min(a[1], b[1])-max(a[0], b[0]))
    return ov/(a[1]-a[0])

def s_space(p, q):
    if p is None: return 1.0
    d = math.hypot(p[0]-q[0], p[1]-q[1])
    return math.exp(-d*d/(2*H*H))

def tables():
    ST = np.array([[s_time(m[1], r[1]) for r in REC] for m in MEN])
    SS = np.array([[s_space(m[2], r[2]) for r in REC] for m in MEN])
    return ST, SS

def score(w):
    ST, SS = tables()
    return w[0]*SN+w[1]*ST+w[2]*SS

def md():
    ST, SS = tables()
    out = []; P = out.append
    P("### 완전 풀이 예제 1: 세 점수를 만들고 합치기")
    P("")
    P("가상의 지명 사전에 기록 네 개(r1~r4)가 있고, 사료에서 뽑은 언급이 세 개(m1~m3)이다. 언급에는 연도 구간과(있다면) 공간 힌트가 붙어 있다. 기록에는 존속 기간과 위치가 있다. 위치는 km 좌표이다.")
    P("")
    P("| 언급 | 시기 | 공간 힌트 |")
    P("|---|---|---|")
    for m in MEN:
        P(f"| {m[0]} | {m[1][0]}~{m[1][1]}년 | " + (f"({m[2][0]}, {m[2][1]})" if m[2] else "없음") + " |")
    P("")
    P("| 기록 | 존속 | 위치 (km) |")
    P("|---|---|---|")
    for r in REC:
        P(f"| {r[0]} | {r[1][0]}~{r[1][1]}년 | ({r[2][0]}, {r[2][1]}) |")
    P("")
    P("**이름 점수** $s_{name}$는 규칙으로 준다: 글자가 같으면 1.0, 한국 한자음이 같고 글자만 다르면 0.8(m1과 r1이 이 경우이다), 이표기(다르게 적은 같은 이름)로 알려져 있으면 0.6, 무관하면 0.1이다. 아래 표는 이 규칙으로 매긴 값이다. 규칙 자체는 약속이므로 책에서 쓸 때는 규칙 표를 따로 싣는다.")
    P("")
    P("| | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{SN[i,j]:.1f}" for j in range(4)) + " |")
    P("")
    P("**시기 점수** $s_{time}=\\dfrac{\\text{언급 구간과 기록 구간이 겹치는 해 수}}{\\text{언급 구간의 길이}}$. 예를 들어 m1(1090~1110, 길이 20년)과 r2(1180~1400)는 겹치는 해가 없으므로 0, r1(1000~1180)과는 20년 전부 겹치므로 20/20$=1$이다. m3(1150~1190년, 길이 40년)과 r1은 1150~1180년의 30년이 겹쳐 30/40$=0.75$이다.")
    P("")
    P("| | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{ST[i,j]:.2f}" for j in range(4)) + " |")
    P("")
    P("**공간 점수** $s_{space}=\\exp(-d^2/2h^2)$, $h=50$ km. m1과 r1의 거리는 $\\sqrt{(140-125)^2+(150-150)^2}=15$ km이므로 $\\exp(-225/5000)=\\exp(-0.045)=0.956$이다. m3처럼 공간 힌트가 없으면 1로 둔다(\"모른다\"를 \"맞다\"로 쓰는 셈이므로 점수가 후하게 나온다는 점을 기억해야 한다).")
    P("")
    P("| | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{SS[i,j]:.3f}" for j in range(4)) + " |")
    P("")
    S = score(W0)
    P("**합산.** $s=0.5\\,s_{name}+0.3\\,s_{time}+0.2\\,s_{space}$. 한 칸을 끝까지 계산하면 m1–r1은 $0.5\\times0.8+0.3\\times1.00+0.2\\times" + f"{SS[0,0]:.3f}={S[0,0]:.3f}$이다. 전체 표는 다음과 같다.")
    P("")
    P("| | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{S[i,j]:.3f}" for j in range(4)) + " |")
    P("")
    P("0.45 미만은 정합 실패로 둔다. 위 표에서 0.45 이상인 칸을 세면 " + f"{int((S>=0.45).sum())}개이다.")
    P("")
    P("### 완전 풀이 예제 2: 욕심쟁이 방법과 헝가리 알고리즘")
    P("")
    # greedy
    Sg = S.copy(); gp = []; used_r = set(); used_m = set()
    flat = sorted([(Sg[i, j], i, j) for i in range(3) for j in range(4)], reverse=True)
    for v, i, j in flat:
        if i in used_m or j in used_r: continue
        gp.append((i, j, v)); used_m.add(i); used_r.add(j)
    ri, ci = linear_sum_assignment(-S)
    P("**욕심쟁이 방법**: 표에서 가장 큰 점수의 쌍을 먼저 고르고, 그 행과 열을 지우고 되풀이한다.")
    P("")
    for i, j, v in gp:
        P(f"- {MEN[i][0]} ↔ {REC[j][0]} ({v:.3f})")
    P(f"- 합: {sum(v for _, _, v in gp):.3f}")
    P("")
    P("**헝가리 알고리즘**은 쌍의 합이 최대가 되는 짝짓기를 찾는다. 아이디어는 \"비용 표에서 행마다 최솟값을 빼고, 열마다 최솟값을 빼고, 0만 지나는 짝짓기를 찾고, 없으면 표를 조정해 0을 더 만든다\"를 되풀이하는 것이다. 우리는 점수를 최대화하므로 각 점수를 (가장 큰 점수 − 점수)로 바꿔 비용으로 만든다. 가장 큰 점수는 " + f"{S.max():.3f}이다.")
    P("")
    C = S.max()-S
    P("| 비용 $=\\max-s$ | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{C[i,j]:.3f}" for j in range(4)) + " |")
    P("")
    P("행마다 최솟값을 뺀 표는 다음과 같다.")
    P("")
    C1 = C-C.min(axis=1, keepdims=True)
    P("| 행 최솟값 뺌 | r1 | r2 | r3 | r4 |")
    P("|---|---|---|---|---|")
    for i, m in enumerate(MEN):
        P(f"| {m[0]} | " + " | ".join(f"{C1[i,j]:.3f}" for j in range(4)) + " |")
    P("")
    unc = C1[:, [1, 3]]
    P(f"각 행에 0이 하나씩 생겼다. 그런데 m1과 m3의 0이 모두 r1 열에 있어 서로 다른 열을 고를 수 없다. 0을 모두 덮는 선이 r1 열과 r3 열의 둘뿐이라 행의 수 3보다 적기 때문이다. 이럴 때는 선이 덮지 않은 칸 중 최솟값 {unc.min():.3f}을 덮이지 않은 칸에서 모두 빼서 새 0을 만든다. 그러면 m3–r4가 0이 되어 세 행이 서로 다른 열의 0을 하나씩 갖게 된다. 짝짓기가 완성된 것이다. 이 표에서 얻은 짝짓기는 " + "; ".join(f"{MEN[i][0]}↔{REC[j][0]}" for i, j in zip(ri, ci)) + f"이며 점수의 합은 {S[ri,ci].sum():.3f}이다(컴퓨터 계산으로 확인).")
    P("")
    if abs(S[ri, ci].sum()-sum(v for _, _, v in gp)) < 1e-9:
        P("이번 표에서는 두 방법의 합이 같다. 욕심쟁이 방법이 늘 틀리는 것은 아니다. 점수가 서로 겹치는 경우에만 갈라진다. 아래 작은 표가 그 예이다.")
    else:
        P(f"욕심쟁이 방법의 합({sum(v for _, _, v in gp):.3f})보다 헝가리 알고리즘의 합({S[ri,ci].sum():.3f})이 크다. m3이 r1에 가장 높은 점수를 주었는데 m1에게도 r1이 거의 유일한 좋은 후보였다. 욕심쟁이 방법은 먼저 눈에 띈 높은 점수(m3–r1)를 잡아 m1을 낮은 점수의 후보로 밀어낸 것이고, 헝가리 알고리즘은 m3을 r4로 보내고 m1이 r1을 갖도록 전체를 조정했다.")
    P("")
    P("| | 기록 a | 기록 b |")
    P("|---|---|---|")
    P("| 언급 1 | 0.90 | 0.80 |")
    P("| 언급 2 | 0.85 | 0.20 |")
    P("")
    P("욕심쟁이: 0.90(1–a)을 먼저 고르고 남은 2–b는 0.20, 합 1.10. 최적: 1–b(0.80)와 2–a(0.85), 합 1.65. 위의 두 방법이 갈라지는 가장 작은 예이다.")
    P("")
    P("### 완전 풀이 예제 3: 가중치를 바꾸면 결과가 변하는가")
    P("")
    P("가중치 $(w_n,w_t,w_s)=(0.5,0.3,0.2)$는 편의상 정한 값이다. 몇 가지로 바꿔 최적 짝짓기가 달라지는지 본다.")
    P("")
    P("| $(w_n,w_t,w_s)$ | m1의 짝 | m2의 짝 | m3의 짝 | 합 |")
    P("|---|---|---|---|---|")
    base_pairs = {i: j for i, j in zip(ri, ci)}
    changed = 0
    for w in [(0.5, 0.3, 0.2), (0.7, 0.2, 0.1), (0.34, 0.33, 0.33), (0.2, 0.3, 0.5), (0.2, 0.6, 0.2)]:
        Sw = score(w); a, b = linear_sum_assignment(-Sw)
        pr = {i: j for i, j in zip(a, b)}
        if pr != base_pairs: changed += 1
        P(f"| ({w[0]}, {w[1]}, {w[2]}) | " + " | ".join(REC[pr[i]][0] for i in range(3)) + f" | {Sw[a,b].sum():.3f} |")
    P("")
    P(f"기준 가중치와 다른 짝짓기를 낸 가중치는 5개 중 {changed}개이다. " + ("0이면 이번 결과는 가중치에 흔들리지 않는다는 뜻이다." if changed == 0 else "달라진 경우가 있으면 그 언급의 짝은 가중치에 의존하는 것이므로 표시하고 단정하지 않는다."))
    P("")
    P("### 완전 풀이 예제 4: 모호성 지수와 시간 조각내기")
    P("")
    P("지명 사전에 \"서도\"라는 이름의 기록이 연도별로 다음과 같이 있다고 하자: 기록 X(1000~1180년, 위치 (125,150)), 기록 Y(1100~1300년, 위치 (300,80)). 두 기록은 1100~1180년의 80년 동안 겹친다.")
    P("")
    P("- 언급의 연도가 1050년이면 이름이 같은 기록 중 시기가 맞는 것은 X뿐이다. 모호성 지수 1. 이름이 곧 장소를 정한다.")
    P("- 언급의 연도가 1140년이면 X와 Y 둘 다 시기가 맞는다. 모호성 지수 2. 이름과 시기로는 어느 곳인지 정할 수 없으므로 공간 점수가 결정한다. 공간 힌트가 (120,160) 근처라면 X가 $\\exp(-125/5000)=0.975$, Y는 거리 $\\sqrt{180^2+80^2}=197$ km이므로 $\\exp(-197^2/5000)=" + f"{math.exp(-(180**2+80**2)/5000):.4f}$이다. 공간 힌트가 없다면 두 기록의 점수가 같아져 결정할 수 없다.")
    P("- 이런 경우 결과에는 \"모호성 지수 2, 공간 힌트에 의존\"이라고 표시한다. 점수가 높다는 사실만으로 확신해서는 안 된다는 경고이다.")

    P("")
    P("### 완전 풀이 예제 5: 시기가 불확실한 언급의 시기 점수")
    P("")
    P("언급의 연도가 정확하지 않을 때는 구간으로 적는다. 시기 점수는 \"언급 구간 가운데 기록과 겹치는 비율\"이므로 구간의 폭이 점수를 좌우한다. 같은 기록 r1(1000~1180년)에 대해 언급 구간을 넓혀 보자.")
    P("")
    P("| 언급 구간 | 길이(년) | r1과 겹치는 해 | 시기 점수 |")
    P("|---|---|---|---|")
    for lo, hi in [(1150, 1170), (1150, 1190), (1150, 1210), (1100, 1260), (1180, 1260)]:
        ov = max(0, min(hi, 1180)-max(lo, 1000))
        P(f"| {lo}~{hi} | {hi-lo} | {ov} | {ov/(hi-lo):.2f} |")
    P("")
    P("구간이 기록의 마지막 해를 넘어 넓어질수록 점수가 떨어진다. 이것은 \"언급이 넓게 적혀 있어 확신이 줄었다\"는 뜻을 자연스럽게 담는다. 그러나 반대의 문제도 있다. 언급 구간이 1180~1260처럼 기록의 끝에 걸치기만 하면 점수가 0이 되어 정합 후보에서 완전히 탈락한다. 연도 오차가 몇 년뿐일 가능성을 생각하면 너무 가혹하다. 그래서 점수를 쓸 때는 \"시기 점수 0\"인 후보도 버리지 말고, 기록의 구간을 앞뒤로 10~20년씩 넓혔을 때의 점수를 함께 계산해 비교한다.")
    P("")
    P("| 기록 구간 | 언급 1180~1260의 시기 점수 |")
    P("|---|---|")
    for pad in (0, 10, 20, 40):
        ov = max(0, min(1260, 1180+pad)-max(1180, 1000))
        P(f"| 1000~{1180+pad} (뒤로 {pad}년 넓힘) | {ov/80:.2f} |")
    P("")
    P("이 표에서 40년을 넓히면 점수가 0.50이 된다. 넓히는 폭도 연구자가 정하는 가정이므로 얼마를 넓혔는지를 결과에 함께 적는다.")
    return "\n".join(out)

if __name__ == "__main__":
    print(md())
