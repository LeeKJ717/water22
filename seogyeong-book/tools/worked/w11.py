"""11장 완전 풀이 예제: 핵밀도, 평활 비율, 나이브 베이즈 우도비, 대역폭 민감도, 글자 대응. 가상 지명 사전."""
import numpy as np, math

# 가상 지명 사전: (이름, x, y) km. 형태소는 이름의 글자.
NAMES = [("평산", 40, 60), ("평천", 70, 80), ("평성", 55, 110), ("산천", 130, 70), ("성산", 150, 120),
         ("양성", 210, 90), ("양천", 240, 140), ("산양", 180, 40), ("평양", 60, 30), ("성천", 120, 150),
         ("천양", 220, 60), ("하평", 30, 100)]
CELLS = {"P": (60, 70), "Q": (150, 90), "R": (230, 100)}
H = 45.0

def rho(m, p, h=H):
    s = 0.0
    for nm, x, y in NAMES:
        if m in nm:
            s += math.exp(-((p[0]-x)**2+(p[1]-y)**2)/(2*h*h))
    return s

def rho_all(p, h=H):
    return sum(math.exp(-((p[0]-x)**2+(p[1]-y)**2)/(2*h*h)) for _, x, y in NAMES)

def rbar(m):
    return sum(1 for nm, _, _ in NAMES if m in nm)/len(NAMES)

def r(m, p, alpha=1.0, h=H):
    return (rho(m, p, h)+alpha*rbar(m))/(rho_all(p, h)+alpha)

def lam(ms, p, alpha=1.0, h=H):
    v = 1.0
    for m in ms:
        v *= r(m, p, alpha, h)/rbar(m)
    return v

