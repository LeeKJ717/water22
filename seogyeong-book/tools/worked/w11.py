    P("")
    P("### 완전 풀이 예제 3: 대역폭을 바꾸면 $\\Lambda$가 얼마나 달라지는가")
    P("")
    P("| $h$ (km) | $\\Lambda(P)$ | $\\Lambda(Q)$ | $\\Lambda(R)$ | 가장 큰 칸 |")
    P("|---|---|---|---|---|")
    for h in (22.5, 45.0, 90.0):
        v = {k: lam(["평", "성"], p, h=h) for k, p in CELLS.items()}
