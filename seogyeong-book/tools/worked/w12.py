"""12장 완전 풀이 예제: 로그/선형 풀링, 의존성 가중, 겹침 계수, 충돌량 K, 하나 빼기. 6칸 가상 세계."""
import numpy as np, math

CELLS = ["c1", "c2", "c3", "c4", "c5", "c6"]
P1 = np.array([0.02, 0.38, 0.38, 0.17, 0.05, 0.00])   # 기법 1: 구간·제약 (영역형)
P2 = np.array([0.03, 0.30, 0.45, 0.17, 0.04, 0.01])   # 기법 2: 기하 보간
P3 = np.array([0.55, 0.05, 0.05, 0.05, 0.28, 0.02])   # 기법 3: 오염된 증거를 쓴 기법
PS = [P1, P2, P3]

def norm(v):
    return v/v.sum()

def fmt(v, n=3):
    return "(" + ", ".join(f"{x:.{n}f}" for x in v) + ")"

def md():
    out = []; P = out.append
    P("### 완전 풀이 예제 1: 세 기법의 지도를 곱하기와 평균하기로 합치기")
    P("")
    P("여섯 칸 c1~c6 위에서 세 기법이 각각 사후확률을 냈다고 하자. 세 번째 기법은 필사 오류가 섞인 증거를 써서 c1과 c5를 높게 본다(가상의 상황이다).")
    P("")
    P("| 기법 | c1 | c2 | c3 | c4 | c5 | c6 |")
    P("|---|---|---|---|---|---|---|")
    for k, p in enumerate(PS, 1):
        P(f"| 기법 {k} | " + " | ".join(f"{x:.2f}" for x in p) + " |")
    P("")
    P("**1단계: 로그 풀링(곱하기), 지수 1.** 칸마다 세 확률을 곱한 뒤 합이 1이 되도록 나눈다.")
    P("")
    prod = P1*P2*P3
    P(f"- 곱: {fmt(prod, 6)}")
    P(f"- 합: {prod.sum():.6f}")
    pl = norm(prod)
    P(f"- 정규화: {fmt(pl)}")
    P("")
    p12 = norm(P1*P2)
    P(f"기법 3의 주장(c1)은 다른 두 기법이 c1을 0.02와 0.03으로 낮게 보았기 때문에 곱에서 {pl[0]:.3f}로 지워졌다. 곱하기에서는 의견이 갈릴 때 **낮게 본 쪽이 결정**한다. c6은 기법 1이 0으로 두어 곱이 0이 되었다. 한편 기법 3은 c2, c3, c4를 모두 같은 0.05로 보았으므로 이 세 칸의 순위는 바뀌지 않았다. 결과의 최대는 c{int(np.argmax(pl))+1}({pl.max():.3f})이고, 기법 1과 2만 곱했을 때의 값 {p12[int(np.argmax(pl))]:.3f}와 비슷하다. 곧 이번 예에서 기법 3은 결과를 크게 바꾸지는 못했다.")
    P("")
    P("**2단계: 선형 풀링(평균하기), $w=(1/3,1/3,1/3)$.**")
    pa = (P1+P2+P3)/3
    P("")
    P(f"- $(0.02+0.03+0.55)/3=0.200$ 등 칸마다 평균: {fmt(pa)}")
    P(f"- 최대는 c{int(np.argmax(pa))+1}, 확률 {pa.max():.3f}. 곱하기보다 완만하고 c1도 {pa[0]:.3f}로 살아 있다.")
    P("")
    P("### 완전 풀이 예제 2: 의존성 가중치")
    P("")
    P("기법 1과 기법 2가 사실상 같은 거리 서술을 쓴다고 하자. 그러면 두 기법은 하나로 보아야 한다. 지수를 $(1/2,\\,1/2,\\,1)$로 준다(기법 1·2는 반 번씩, 기법 3은 한 번). 계산 과정은 다음과 같다.")
    P("")
    w = np.array([0.5, 0.5, 1.0])
    P("| 칸 | $p_1^{1/2}$ | $p_2^{1/2}$ | $p_3^{1}$ | 곱 |")
    P("|---|---|---|---|---|")
    vals = np.array([P1**0.5*P2**0.5*P3**1.0]).ravel()
    for i, c in enumerate(CELLS):
        P(f"| {c} | {P1[i]**0.5:.3f} | {P2[i]**0.5:.3f} | {P3[i]:.3f} | {vals[i]:.4f} |")
    pd_ = norm(vals)
    P("")
    P(f"정규화하면 {fmt(pd_)}이다. 지수를 모두 1로 두었을 때의 {fmt(pl)}과 견주면 기법 1·2가 같은 증거를 두 번 센 효과가 줄어 c2, c3 쪽이 올라간다. 최대는 c{int(np.argmax(pd_))+1}({pd_.max():.3f})이다. 지수의 선택은 판단이므로 DB에 근거를 적는다.")
    P("")
    P("### 완전 풀이 예제 3: 겹침 계수와 부딪침 행렬")
    P("")
    P("겹침 $\\mathrm{OVL}(p,q)=\\sum\\min(p,q)$를 모든 쌍에 대해 구한다. 기법 1과 2의 예를 끝까지 적으면 칸별 작은 쪽은 $\\min$ = " + ", ".join(f"{min(a,b):.2f}" for a, b in zip(P1, P2)) + f"이고 합은 {np.minimum(P1,P2).sum():.2f}이다.")
    P("")
    P("| | 기법 1 | 기법 2 | 기법 3 |")
    P("|---|---|---|---|")
    for i in range(3):
        P(f"| 기법 {i+1} | " + " | ".join(f"{np.minimum(PS[i],PS[j]).sum():.2f}" for j in range(3)) + " |")
    P("")
    P("기법 3이 다른 두 기법과 모두 낮게 겹친다(0.2대). 이 행렬만 보아도 기법 3이 의심스럽다. 다만 \"겹치지 않는다\"가 곧 \"틀렸다\"는 뜻은 아니다. 다른 두 기법이 같은 가정을 공유해서 서로 닮았을 수도 있기 때문이다. 이 가능성은 증거 출처 표로 확인한다.")
    P("")
    P("### 완전 풀이 예제 4: 하나 빼기")
    P("")
    P("기법 하나를 빼고 둘을 곱해 합친 결과를 전체(셋을 곱한 결과)와 견준다. 같은 방법으로 겹침 계수를 계산한다.")
    P("")
    P("| 뺀 기법 | 남은 둘을 곱한 결과 | 최대 칸 | 전체 결과와의 겹침 |")
    P("|---|---|---|---|")
    for k in range(3):
        rest = [PS[i] for i in range(3) if i != k]
        v = norm(rest[0]*rest[1])
        P(f"| 기법 {k+1} | {fmt(v)} | c{int(np.argmax(v))+1} | {np.minimum(v,pl).sum():.2f} |")
    P("")
    P("기법 3을 빼도 전체 결과와의 겹침이 0.95로 거의 같으므로 곱하기 결과는 기법 3에 거의 기대지 않는다. 반대로 기법 1이나 기법 2를 빼면 겹침이 0.65~0.67로 떨어진다. 이 둘이 결과를 좌우하고 있다는 뜻이며, 두 기법이 같은 증거를 공유한다면 그 증거가 두 번 세어졌을 가능성이 있다(예제 2). 기법 3의 불일치는 곱하기의 결과가 아니라 앞의 부딪침 행렬(겹침 0.22)에서 드러난다. 하나 빼기와 부딪침 행렬은 서로 다른 것을 보여 주므로 함께 보고한다. 하나 빼기에서 겹침이 크게 떨어지는 기법이 나오면 14장의 절차로 그 기법의 입력 증거를 점검한다.")
    P("")
    P("### 완전 풀이 예제 5: 충돌량 $K$를 손으로 계산하기")
    P("")
    P("세 기법의 95% 영역을 칸의 집합으로 적는다: $A_1=\\{c2,c3,c4\\}$, $A_2=\\{c2,c3,c4\\}$, $A_3=\\{c1,c5\\}$. 각 기법은 자기 영역에 0.9, \"모른다\"(전체 칸 집합)에 0.1의 믿음을 둔다. 두 기법의 믿음을 합칠 때, 교집합이 비면 충돌이다.")
    P("")
    P("**기법 1과 2**: 영역이 같으므로 교집합 $A_1\\cap A_2=\\{c2,c3,c4\\}$는 비어 있지 않다. 충돌 $K_{12}=0$. 합친 믿음은 $A_1$에 $0.9\\times0.9+0.9\\times0.1+0.1\\times0.9=0.99$, 모른다에 $0.1\\times0.1=0.01$이다.")
    P("")
    P("**(기법 1·2 결과)와 기법 3**: 영역 $A_{12}=\\{c2,c3,c4\\}$에 0.99, 모른다에 0.01인 믿음과 $A_3=\\{c1,c5\\}$에 0.9, 모른다에 0.1인 믿음을 합친다. 교집합이 빈 쌍은 $A_{12}\\times A_3$ 하나이다.")
    P("")
    P("- 충돌량 $K=0.99\\times0.9=0.891$")
    P("- 규칙대로 $1-K=0.109$로 나누면: $A_{12}\\cap(\\text{모른다})=A_{12}$ 쪽 믿음 $0.99\\times0.1/0.109=0.908$, $A_3$ 쪽 $0.01\\times0.9/0.109=0.083$, 모른다 쪽 $0.01\\times0.1/0.109=0.009$")
    P("")
    P("$K=0.891$은 매우 크다. 정면으로 부딪친 두 의견을 합쳤다는 경보이다. 합친 결과는 $A_{12}$ 쪽에 0.908로 쏠렸지만, 이 값을 \"확률\"로 받아들이면 안 된다. 원래 충돌의 크기(0.891)를 지워 버린 결과이기 때문이다. 그래서 이 책은 $K$를 결과가 아니라 **경보**로만 쓴다. 이 예에서는 $K>0.5$이면 합치지 않고 14장의 절차로 원인을 찾는다는 기준을 둔다(기준값 0.5는 약속이다).")
    P("")
    P("자데가 지적한 이상한 경우도 숫자로 확인해 보자. 기법 A는 영역 $X$에 0.99, 영역 $Y$에 0.01, 기법 B는 영역 $Z$에 0.99, 영역 $Y$에 0.01을 둔다($X,Y,Z$는 서로 겹치지 않음). 교집합이 비어 있지 않은 쌍은 $Y\\cap Y$뿐이므로 $K=1-0.01\\times0.01=0.9999$이고, 규칙대로 나누면 $Y$에 $0.0001/0.0001=1$이 된다. 두 기법 모두 거의 믿지 않은 $Y$가 확률 1이 되는 이 결과가 \"이상하다\"는 지적의 핵심이다.")

    P("")
    P("### 완전 풀이 예제 6: 두 기법이 서로 다른 곳을 가리킬 때")
    P("")
    P("여섯 칸 위에서 기법 X는 c1 근처를, 기법 Y는 c5 근처를 가리킨다고 하자(둘 다 믿을 만하지만 서로 부딪친다).")
    PX = np.array([0.50, 0.30, 0.10, 0.05, 0.03, 0.02]); PY = np.array([0.02, 0.03, 0.10, 0.25, 0.45, 0.15])
    P("")
    P("| 방법 | c1 | c2 | c3 | c4 | c5 | c6 |")
    P("|---|---|---|---|---|---|---|")
    P("| 기법 X | " + " | ".join(f"{v:.2f}" for v in PX) + " |")
    P("| 기법 Y | " + " | ".join(f"{v:.2f}" for v in PY) + " |")
    lg = norm(PX*PY); ln_ = (PX+PY)/2
    P("| 곱하기(로그 풀링) | " + " | ".join(f"{v:.3f}" for v in lg) + " |")
    P("| 평균하기(선형 풀링) | " + " | ".join(f"{v:.3f}" for v in ln_) + " |")
    P("")
    P(f"- **곱하기**: 두 기법이 모두 어느 정도 인정하는 칸이 이긴다. 최대는 c{int(np.argmax(lg))+1}({lg.max():.3f})이다. 곱하기는 X도 Y도 가장 높게 보지 않은 \"타협점\"(c2~c4)을 평균하기보다 크게 올려 분포를 평평하게 만든다. 서로 다른 곳을 가리키는 두 증거 사이에 참 위치가 있다는 보장은 없으므로 이 결과는 위험하다.")
    P(f"- **평균하기**: 두 봉우리(c1 {ln_[0]:.3f}, c5 {ln_[4]:.3f})가 그대로 남는다. 최대는 c{int(np.argmax(ln_))+1}({ln_.max():.3f})이다. 이 결과는 \"두 기법이 다른 곳을 가리키니 둘 다 가능하다\"고 정직하게 말한다.")
    ovl = np.minimum(PX, PY).sum()
    P(f"- 겹침 계수는 {ovl:.2f}로 낮다. 이 경우 책의 절차는 곱하기 결과를 쓰지 않고 \"합의 영역 없음\"으로 보고하고 14장의 원인 추적으로 넘어가는 것이다.")
    P("")
    P("곱하기가 타협점을 올리는 현상을 숫자로 확인하자. 곱한 값 중 c3은 $0.10\\times0.10=0.010$으로 c1의 $0.50\\times0.02=0.010$과 같고 c5의 $0.03\\times0.45=0.0135$와도 비슷하다. 어느 쪽도 지배적이지 않으므로 정규화한 뒤 여러 칸이 비슷한 크기로 남는다. 곧 \"합의\"가 아니라 \"서로의 약한 칸이 겹치는 곳\"이 결과가 된 것이다.")
    P("")
    P("### 완전 풀이 예제 7: 지수 $w$를 바꾸면 확신이 어떻게 달라지는가")
    P("")
    P("예제 1의 세 기법에서 지수를 모두 같은 $w$로 놓고 $w=1,\\ 1/2,\\ 1/3$을 비교한다. 지수는 곧 \"각 기법을 몇 번 센 것으로 치는가\"이다. 지수가 작을수록 확신이 줄어든다.")
    P("")
    P("| 지수 $w$ | c1 | c2 | c3 | c4 | c5 | c6 | 최대 확률 | 엔트로피(비트) |")
    P("|---|---|---|---|---|---|---|---|---|")
    for wv in (1.0, 0.5, 1/3):
        v = norm((P1**wv)*(P2**wv)*(P3**wv))
        H_ = -sum(x*math.log2(x) for x in v if x > 0)
        P(f"| {wv:.2f} | " + " | ".join(f"{x:.3f}" for x in v) + f" | {v.max():.3f} | {H_:.2f} |")
    P("")
    P("엔트로피는 $-\\sum p\\log_2 p$로, 흩어진 정도를 비트로 나타낸 값이다. 지수가 작아질수록 엔트로피가 커진다(분포가 평평해진다). 지수의 선택이 곧 확신의 크기를 정한다는 점에서, 이 선택을 근거와 함께 DB에 기록하고 여러 값으로 비교하는 것이 정직한 보고이다.")
    return "\n".join(out)

if __name__ == "__main__":
    print(md())
