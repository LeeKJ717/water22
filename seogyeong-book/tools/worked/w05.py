"""5장 완전 풀이 예제: 구간 연산·공유 단위·제약 전파·최대 제약 만족. 모든 수치는 이 파일을 실행해 계산한다."""
import numpy as np, math

def md():
    A, B, C = (0, 0), (300, 0), (150, 300)
    T = (130, 170); ut = 0.42
    dist = lambda p, q: math.hypot(p[0]-q[0], p[1]-q[1])
    dT = [dist(T, r) for r in (A, B, C)]
    L = [510, 570, 310]
    U = (0.36, 0.48); E = (0.90, 1.10)
    out = []
    P = out.append
    P("### 완전 풀이 예제 1: 세 개의 거리 서술로 영역 만들기")
    P("")
    P("이 예제는 가상 세계에서 계산한 것이며 서경의 결과가 아니다. 기준 지명 세 곳과 목표 지명 하나가 있다고 하자. 기준 지명의 좌표는 $A=(0,0)$, $B=(300,0)$, $C=(150,300)$ km이다. 사료에는 목표 지명이 A에서 510리, B에서 570리, C에서 310리라고 적혀 있다. 가상 세계의 참 위치는 $(130,170)$ km, 참 단위 길이는 $0.42$ km/리로 정해 두었지만 계산하는 사람은 이 값을 모른다고 가정한다. 알고 있는 것은 단위가 $U=[0.36,\\,0.48]$ km/리 안에 있다는 것과, 기록자의 어림 오차가 $\\pm10\\%$, 곧 곱하기 인자 $E=[0.90,\\,1.10]$ 안이라는 것뿐이다.")
    P("")
    P("**1단계: 숫자 하나를 구간으로 바꾼다.** 구간의 곱셈 규칙에 따라 아래끝은 아래끝끼리, 위끝은 위끝끼리 곱한다(모두 양수이므로 네 조합 중 최소와 최대가 그렇게 된다).")
    P("")
    rows = []
    for nm, l in zip("ABC", L):
        lo, hi = l*U[0]*E[0], l*U[1]*E[1]
        rows.append((nm, l, lo, hi))
        P(f"- 기준 {nm}: ${l}\\times[0.36,0.48]\\times[0.90,1.10]$ 이므로 아래끝 $={l}\\times0.36\\times0.90={lo:.1f}$ km, 위끝 $={l}\\times0.48\\times1.10={hi:.1f}$ km. 곧 $d_{nm}\\in[{lo:.1f},\\,{hi:.1f}]$ km.")
    P("")
    P("구간의 폭은 기준 A가 " + f"{rows[0][3]-rows[0][2]:.1f}" + " km이다. 서술 하나가 이렇게 넓은 고리 모양 영역을 만든다. 고리의 안쪽 반지름이 아래끝, 바깥 반지름이 위끝이다.")
    P("")
    P("**2단계: 고리를 겹친다(독립으로 다룰 때).** 칸 $\\mathbf{p}$가 해 영역에 들려면 세 고리 안에 모두 있어야 한다. 2.5 km 칸으로 나눈 격자에서 세 조건을 모두 만족하는 칸을 세었다.")
    # grid
    xs = np.arange(0, 301, 2.5); ys = np.arange(0, 301, 2.5)
    X, Y = np.meshgrid(xs, ys)
    ds = [np.hypot(X-r[0], Y-r[1]) for r in (A, B, C)]
    ind = np.ones_like(X, bool)
    for d, (_, l, lo, hi) in zip(ds, rows):
        ind &= (d >= lo) & (d <= hi)
    cell = 2.5*2.5
    a_ind = ind.sum()*cell
    P("")
    P(f"- 독립 처리 해 영역의 넓이: 약 {a_ind:,.0f} km². (칸 한 변 2.5 km, 칸 수 {int(ind.sum())}개 × 6.25 km²)")
    P("")
    P("**3단계: 같은 자를 하나로 묶는다(공유 단위).** 세 서술은 같은 기록 체계의 자로 적혔으므로 $u$는 하나다. 칸 $\\mathbf{p}$에서 기준 $k$까지의 실제 거리를 $d_k$, 사료 수치를 $L_k$라 하면 $d_k=L_k\\,u\\,e_k$, $e_k\\in[0.90,1.10]$이다. 이것을 $u$에 대해 풀면 $u\\in[\\,d_k/(1.10L_k),\\ d_k/(0.90L_k)\\,]$이다. 서술이 셋이므로 이 구간 셋과 처음의 $U$가 **공통으로 겹치는 $u$가 있어야** 칸이 살아남는다.")
    P("")
    # example cell: truth
    p0 = (130, 170)
    ex = []
    for nm, l, r in zip("ABC", L, (A, B, C)):
        d = dist(p0, r)
        ex.append((nm, l, d, d/(1.10*l), d/(0.90*l)))
    P("실제로 참 위치 $(130,170)$ 칸에서 계산해 보자.")
    P("")
    for nm, l, d, lo, hi in ex:
        P(f"- {nm}: $d={d:.1f}$ km, $L={l}$리 → $u\\in[{d:.1f}/(1.10\\times{l}),\\ {d:.1f}/(0.90\\times{l})]=[{lo:.4f},\\ {hi:.4f}]$")
    lo = max([0.36]+[e[3] for e in ex]); hi = min([0.48]+[e[4] for e in ex])
    P("")
    P(f"네 구간의 아래끝 중 가장 큰 값은 ${lo:.4f}$, 위끝 중 가장 작은 값은 ${hi:.4f}$이다. ${lo:.4f}\\le{hi:.4f}$이므로 겹침이 있고($u\\in[{lo:.4f},\\,{hi:.4f}]$), 이 칸은 살아남는다. 반대로 겹침이 비면(아래끝의 최대값이 위끝의 최소값보다 크면) 그 칸은 버린다.")
    # shared grid
    lo_g = np.full_like(X, 0.36); hi_g = np.full_like(X, 0.48)
    for d, (_, l, _, _) in zip(ds, rows):
        lo_g = np.maximum(lo_g, d/(1.10*l)); hi_g = np.minimum(hi_g, d/(0.90*l))
    sh = lo_g <= hi_g
    a_sh = sh.sum()*cell
    P("")
    P(f"- 공유 단위 해 영역의 넓이: 약 {a_sh:,.0f} km² (칸 {int(sh.sum())}개).")
    P(f"- 독립 처리 {a_ind:,.0f} km² 대비 **{a_sh/a_ind*100:.0f}%**로 줄었다. 줄어든 만큼이 \"같은 자를 세 번 다시 모르는 척한 손해\"이다.")
    P(f"- 참 위치는 두 영역에 모두 들어 있다(독립 처리: {'예' if ind[int(170/2.5), int(130/2.5)] else '아니오'}, 공유 단위: {'예' if sh[int(170/2.5), int(130/2.5)] else '아니오'}). 영역이 참을 놓치지 않았다는 점이 이 방법의 정직성 조건이다.")
    P("")
    # 4: dependency numbers for pair difference
    P("**4단계: 차이로 보는 같은 현상.** A와 B의 서술 차이를 보면 공유의 효과를 손으로 확인할 수 있다. 두 서술의 수치 차이 $570-510=60$리는 $u$를 공유하면 $60u\\in[21.6,\\,28.8]$ km로 폭 7.2 km이지만, $u$를 따로 취급하면 $570\\times[0.36,0.48]-510\\times[0.36,0.48]=[205.2-244.8,\\ 273.6-183.6]=[-39.6,\\ 90.0]$ km로 폭이 129.6 km가 된다. 폭의 비는 $129.6/7.2=18$배이다.")
    P("")
    # example 2: propagation 1D
    P("### 완전 풀이 예제 2: 미지 지명이 둘일 때의 제약 전파")
    P("")
    P("가상의 길 위에서 서경 후보 $X$와 관문 $Y$가 있다고 하자. 위치는 길의 시작점에서 잰 km이다. 사료에서 얻은 조건은 세 개다. (가) $X\\in[100,\\,200]$, (나) $Y-X\\in[50,\\,80]$(관문은 서경에서 50~80 km 앞), (다) $Y\\in[120,\\,230]$. 호 일관성은 조건 하나로 한 변수의 범위를 깎고, 깎인 범위를 다른 조건에 다시 넣는 일을 더 줄지 않을 때까지 되풀이한다.")
    P("")
    X_ = [100.0, 200.0]; Y_ = [120.0, 230.0]
    step = 0
    P("| 회차 | 사용한 식 | $X$ 범위 | $Y$ 범위 |")
    P("|---|---|---|---|")
    P(f"| 0 | 처음(가)(다) | [{X_[0]:.0f}, {X_[1]:.0f}] | [{Y_[0]:.0f}, {Y_[1]:.0f}] |")
    while True:
        step += 1
        oldX, oldY = X_[:], Y_[:]
        # Y = X + D, D in [50,80]
        newY = [max(Y_[0], X_[0]+50), min(Y_[1], X_[1]+80)]
        P(f"| {step}a | $Y\\in X+[50,80]$ | [{X_[0]:.0f}, {X_[1]:.0f}] | [{newY[0]:.0f}, {newY[1]:.0f}] |")
        Y_ = newY
        newX = [max(X_[0], Y_[0]-80), min(X_[1], Y_[1]-50)]
        P(f"| {step}b | $X\\in Y-[50,80]$ | [{newX[0]:.0f}, {newX[1]:.0f}] | [{Y_[0]:.0f}, {Y_[1]:.0f}] |")
        X_ = newX
        if X_ == oldX and Y_ == oldY:
            break
    P("")
    P(f"고정점에서 $X\\in[{X_[0]:.0f},\\,{X_[1]:.0f}]$, $Y\\in[{Y_[0]:.0f},\\,{Y_[1]:.0f}]$이다. 처음의 $X$ 폭 100 km가 {X_[1]-X_[0]:.0f} km로, $Y$ 폭 110 km가 {Y_[1]-Y_[0]:.0f} km로 줄었다. 새 사료를 한 줄도 더하지 않았는데 조건들이 서로를 좁혀 준 것이다. 이것이 \"증거를 연결하면 정보가 는다\"의 가장 단순한 모습이다. 단, 구간이 줄었다고 해서 가운데가 더 그럴듯한 것은 아니다. 구간은 \"가능/불가능\"만 말한다.")
    P("")
    # example 3: max-CSP
    P("### 완전 풀이 예제 3: 틀린 증거가 하나 섞였을 때(최대 제약 만족)")
    P("")
    P("예제 1에 네 번째 서술을 더한다. 기준 $D=(300,300)$에서 \"목표가 180리 떨어져 있다\"는 서술이다. 참 거리는 $\\sqrt{170^2+130^2}=214.0$ km로 사실은 약 510리인데 필사 과정에서 180리로 잘못 적힌 것이다($U,E$는 같다). 고리는 $180\\times0.36\\times0.90=58.3$ km부터 $180\\times0.48\\times1.10=95.0$ km까지로, 참 위치가 들어 있지 않다.")
    D = (300, 300)
    d4 = np.hypot(X-D[0], Y-D[1])
    ok = [(d >= lo_) & (d <= hi_) for d, (lo_, hi_) in zip(ds+[d4], [(r[2], r[3]) for r in rows]+[(180*0.36*0.9, 180*0.48*1.1)])]
    cnt = sum(o.astype(int) for o in ok)
    allok = (cnt == 4).sum()*cell
    P("")
    P(f"- 네 조건을 **모두** 지키는 칸의 넓이: {allok:,.0f} km² (칸 {int((cnt==4).sum())}개). 비었거나 참과 먼 곳만 남는다.")
    P(f"- 세 조건까지 지키는 칸의 넓이: {((cnt>=3).sum()*cell):,.0f} km².")
    tr = cnt[int(170/2.5), int(130/2.5)]
    P(f"- 참 위치 $(130,170)$ 칸이 지키는 조건 수: {int(tr)}개. 하나(네 번째)만 어긴다.")
    P("")
    P("이런 상황에서 \"모두 겹침\"은 참을 버린다. 최대 제약 만족은 \"어긴 조건이 가장 적은 칸\"을 남긴다. 위 계산에서 세 조건을 지키는 칸들 속에 참 위치가 들어 있다. 그리고 **어느 조건을 버렸는가를 반드시 기록**한다. 버린 조건이 사실은 옳고 나머지 셋이 틀렸을 수도 있기 때문이다. 이 선택은 9장 이후의 다른 기법과 대조해서 확인한다.")

    P("")
    P("### 완전 풀이 예제 4: 구간을 연달아 곱하고 나누기")
    P("")
    P("사료에 \"어느 성에서 서경까지 6일 길\"이라고 적혀 있다고 하자. 하루 걷는 거리는 $[25,\\,40]$ km, 길이 구불구불한 정도를 나타내는 우회 계수(직선 거리 대비 실제 길이 비)는 $[1.1,\\,1.4]$로 본다. 직선 거리 $D$를 구한다.")
    P("")
    P("**1단계: 실제 걸은 거리.** $6\\times[25,40]=[150,\\,240]$ km.")
    P("")
    P("**2단계: 직선 거리.** 실제 길이 $=D\\times$ 우회 계수이므로 $D=\\text{실제 길이}\\div\\text{우회 계수}$. 구간의 나눗셈은 \"나누는 구간의 역수 구간을 곱한다\"이다. $1/[1.1,1.4]=[1/1.4,\\,1/1.1]=[0.714,\\,0.909]$. 따라서")
    P("")
    lo = 150*(1/1.4); hi = 240*(1/1.1)
    P(f"$D=[150,240]\\times[0.714,0.909]=[{lo:.1f},\\ {hi:.1f}]$ km.")
    P("")
    P(f"결과는 폭이 {hi-lo:.0f} km인 구간이다. 가장 짧은 경우(하루 25 km, 우회가 가장 큼)와 가장 긴 경우(하루 40 km, 우회가 가장 작음)를 끝에 놓은 것이다. 구간 연산은 이처럼 불확실한 값을 연달아 곱할수록 폭이 빠르게 커진다. 같은 계산을 \"가운데 값\"으로만 하면 $6\\times32.5/1.25=156$ km로 한 점이 나오지만, 그 점이 얼마나 믿을 만한지는 알 수 없다.")
    P("")
    P("**3단계: 해 영역으로.** 기준 지명에서 직선 거리가 $[{:.1f},\\ {:.1f}]$ km인 칸이 허용된다. 안쪽 반지름 {:.1f} km, 바깥 반지름 {:.1f} km의 고리 면적은 $\\pi({:.1f}^2-{:.1f}^2)$로 약 {:,.0f} km²이다. 다른 증거가 없다면 서경 후보는 이 넓이 안 어디에나 있을 수 있다는 뜻이다.".format(lo, hi, lo, hi, hi, lo, math.pi*(hi**2-lo**2)))
    P("")
    P("**부호가 섞이는 경우.** 구간이 0을 지나가면 네 조합을 모두 계산해야 한다. 예를 들어 방위 오차가 $[-10,\\,15]$도이고 이를 $[2,3]$배로 늘려야 한다면 네 조합 $-20,\\ -30,\\ 30,\\ 45$ 중 가장 작은 $-30$과 가장 큰 $45$를 취해 $[-30,\\ 45]$도이다. 아래끝끼리, 위끝끼리 곱하는 지름길은 구간이 양수일 때만 맞다.")

    P("")
    P("### 완전 풀이 예제 5: 방위 서술을 부채꼴 영역으로 바꾸기")
    P("")
    P("사료에 \"기준 A의 서쪽에서 조금 북으로 기운 방향\"이라고 적혀 있다고 하자. 서쪽을 $180^\\circ$(동쪽이 $0^\\circ$, 반시계 방향으로 잰 각)로 하고 \"조금 북으로 기운\"을 $+5^\\circ$에서 $+25^\\circ$로 해석한다. 방위 구간은 $[185^\\circ,\\ 205^\\circ]$가 아니라 북쪽으로 기울면 각이 작아지므로 $[155^\\circ,\\ 175^\\circ]$이다. 거리 구간이 $[165,\\ 269]$ km(예제 1의 A)이면 영역은 반지름 165~269 km의 고리 가운데 각이 $155^\\circ$~$175^\\circ$인 부분(부채꼴 고리)이다.")
    P("")
    th1, th2 = math.radians(155), math.radians(175)
    area = 0.5*(th2-th1)*(269.3**2-165.2**2)
    P(f"**넓이.** 부채꼴 고리의 넓이는 $\\tfrac12(\\theta_2-\\theta_1)(R^2-r^2)$이다(각은 라디안). $\\theta_2-\\theta_1=20^\\circ=0.349$ rad, $R=269.3$, $r=165.2$이므로 $0.5\\times0.349\\times({269.3**2:,.0f}-{165.2**2:,.0f})$로 약 {area:,.0f} km²이다. 같은 거리 구간만 쓴 전체 고리의 넓이 {math.pi*(269.3**2-165.2**2):,.0f} km²의 {area/(math.pi*(269.3**2-165.2**2))*100:.1f}%이다. 방위 하나를 더했을 뿐인데 후보 영역이 18분의 1 가까이로 줄었다.")
    P("")
    P("**꼭짓점 좌표로 확인.** 부채꼴 고리의 네 모서리는 다음과 같다(A를 원점, 동쪽 $x$, 북쪽 $y$).")
    P("")
    P("| 모서리 | 각 | 반지름 (km) | $x=R\\cos\\theta$ | $y=R\\sin\\theta$ |")
    P("|---|---|---|---|---|")
    for lab, th, R in (("안쪽 · 작은 각", 155, 165.2), ("안쪽 · 큰 각", 175, 165.2), ("바깥쪽 · 작은 각", 155, 269.3), ("바깥쪽 · 큰 각", 175, 269.3)):
        P(f"| {lab} | {th}° | {R} | {R*math.cos(math.radians(th)):.1f} | {R*math.sin(math.radians(th)):.1f} |")
    P("")
    P("모서리의 $x$가 모두 음수(서쪽)이고 $y$가 양수(북쪽)이므로 서북쪽의 좁은 영역이다. 이렇게 \"방향의 말\"도 각도의 구간으로 옮기면 거리 구간과 똑같이 겹칠 수 있다. 다만 \"조금\"을 몇 도로 읽을지는 해석이므로, 읽는 폭을 달리한 결과를 함께 보인다.")
    return "\n".join(out)

if __name__ == "__main__":
    print(md())
