def add_caps(md, ch):
    L = md.split("\n"); out = []; k = 0
    for i, ln in enumerate(L):
        if ln.startswith("|") and i + 1 < len(L) and L[i + 1].startswith("|---") and (i == 0 or not L[i - 1].startswith("|")):
            cap = CAPS[ch][k]; k += 1
            out += ["Table: " + cap, ""]
        out.append(ln)
    assert k == len(CAPS[ch]), (ch, k, len(CAPS[ch]))
    return "\n".join(out)

def block(ch):
    mod = importlib.import_module("w" + ch)
    body = mod.md()
    body = re.sub(r"(?m)^(\|[^\n]*\n\|---[^\n]*\n(?:\|[^\n]*\n)*)(?=[^|\n])", lambda m: m.group(1) + "\n", body + "\n")
    body = add_caps(body, ch)
    return "<!-- worked:start -->\n### 수치로 따라가는 완전 풀이\n\n" + INTRO[ch] + "\n\n" + body.strip() + "\n\n<!-- worked:end -->\n\n"

def main():
    for ch, name in CH.items():
        p = os.path.join(ROOT, "원고", name + ".md")
        t = open(p, encoding="utf-8").read()
        t = re.sub(r"<!-- worked:start -->.*?<!-- worked:end -->\n\n", "", t, flags=re.S)
        key = "### 이 장의 식을 응용하려면"
        if key not in t:
            key = "@@refs ch" + ch + "@@"
        assert key in t, name
        t = t.replace(key, block(ch) + key, 1)
        open(p, "w", encoding="utf-8").write(t)
        print(name, len(t))

if __name__ == "__main__":
    main()
